interface MessageContent {
  role: 'user' | 'assistant';
  content: string;
}

interface ConversationContext {
  mood?: string;
  conversationHistory?: MessageContent[];
  userName?: string;
}

export async function generateAIResponse(
  userMessage: string,
  context?: ConversationContext
): Promise<{ response: string; isCrisis: boolean; mood?: string }> {
  try {
    await ensureOllamaReady();
    
    // Check cache first (OPTIMIZATION)
    const cacheKey = generateAICacheKey(userMessage, context);
    const cachedResponse = getCachedResponse(cacheKey);
    if (cachedResponse) {
      console.log('✅ Cache hit for:', userMessage.substring(0, 30) + '...');
      return cachedResponse;
    }

    // Ensure model is loaded
    await ensureModelLoaded();

    // Логируем входящее сообщение
    console.log('\n🔍 DEBUG: generateAIResponse called');
    console.log('📝 User message:', userMessage);
    console.log('🎭 Mood:', context?.mood);
    console.log('📜 History length:', context?.conversationHistory?.length || 0);

    // Проверка на пустое сообщение
    if (!userMessage || userMessage.trim().length === 0) {
      throw new Error('Сообщение не может быть пустым');
    }

    // Определяем, кризис ли это
    const isCrisis = detectCrisisKeywords(userMessage);
    if (isCrisis) {
      console.log('🆘 CRISIS DETECTED!');
    }

    // Строим системный промпт с учетом имени пользователя
    let systemPrompt = SYSTEM_PROMPT;
    if (context?.userName) {
      systemPrompt = `${SYSTEM_PROMPT}\n\nИМЯ ПОЛЬЗОВАТЕЛЯ: ${context.userName}. `;
      
      // Приветствие только для первого сообщения (когда нет истории)
      if (!context?.conversationHistory || context.conversationHistory.length === 0) {
        systemPrompt += `Поприветствуй пользователя по имени в начале ответа. `;
      } else {
        systemPrompt += `НЕ приветствуй пользователя снова - вы уже общаетесь. Продолжай разговор естественно. `;
      }
      
      console.log('👤 User name:', context.userName);
      console.log('💬 Is first message:', !context?.conversationHistory || context.conversationHistory.length === 0);
    }

    // Если есть mood - добавляем это в контекст
    let enhancedMessage = userMessage;
    if (context?.mood) {
      enhancedMessage = `[Текущее настроение пользователя: ${context.mood}]\n\n${userMessage}`;
    }

    console.log('📤 Enhanced message:', enhancedMessage.substring(0, 100) + '...');

    // Конвертируем историю сообщений в правильный формат для Ollama
    const messages: MessageContent[] = [
      ...((context?.conversationHistory || []) as MessageContent[]),
      { role: 'user', content: enhancedMessage }
    ];

    console.log('🔄 Sending request to Ollama. History size:', context?.conversationHistory?.length || 0);

    // Отправляем запрос к Ollama
    let responseText = '';
    try {
      const timeoutPromise = new Promise((_, reject) =>
        setTimeout(() => reject(new Error('Ollama timeout (180s)')), 180000)
      );

      const responsePromise = ollamaClient.post('/api/chat', {
        model: config.ollamaModel,
        messages: [
          {
            role: 'system',
            content: systemPrompt
          },
          ...messages
        ],
        stream: false,
        options: {
          temperature: 0.5,  // Lower temperature = more consistent grammar
          top_p: 0.85,       // More focused responses
          top_k: 30,         // Smaller vocabulary pool for better accuracy
          repeat_penalty: 1.2  // Avoid repetition
        }
      });

      const result = await Promise.race([responsePromise, timeoutPromise]) as any;
      
      console.log('✅ Response received from Ollama');

      if (result.data?.message?.content) {
        responseText = result.data.message.content;
      } else {
        console.error('❌ Unexpected response format:', result.data);
        throw new Error('Неожиданный формат ответа от Ollama');
      }

    } catch (timeoutError) {
      console.error('⏱️ Timeout or send error:', timeoutError);
      throw new Error('Ollama timeout - попробуйте позже');
    }

    console.log('📥 Response text length:', responseText?.length || 0);
    console.log('📥 Response preview:', (responseText || '').substring(0, 100) + '...');

    // Проверка на пустой ответ
    if (!responseText || responseText.trim().length === 0) {
      console.warn('⚠️ WARNING: Empty response from Ollama');
      throw new Error('Ollama вернула пустой ответ - попробуйте позже');
    }

    // Проверка на ненормальный ответ (слишком короткий)
    if (responseText.trim().length < 5) {
      console.warn('⚠️ WARNING: Response too short:', responseText);
      throw new Error('AI ответ слишком короткий - попробуйте переформулировать');
    }

    console.log('🎉 Success! Returning response');

    const result = {
      response: responseText,
      isCrisis,
      mood: context?.mood,
    };

    // Cache the response (OPTIMIZATION)
    cacheResponse(cacheKey, result, 3600); // Cache for 1 hour
    
    return result;
  } catch (error) {
    console.error('❌ ERROR in generateAIResponse:');
    console.error('   Message:', error instanceof Error ? error.message : String(error));
    console.error('   Stack:', error instanceof Error ? error.stack : 'no stack');
    throw error;
  }
}

// Функция для определения кризисных ключевых слов
export function detectCrisisKeywords(text: string): boolean {
  const crisisKeywords = [
    'суицид',
    'убить себя',
    'не хочу жить',
    'умереть',
    'нет смысла жить',
    'лучше бы я умер',
    'порежу',
    'режу себя',
    'самоповреждение',
    'конец всему',
    'покончить с собой',
    'душевная боль невыносима',
    'не могу больше',
    'хочу исчезнуть',
  ];

  const lowerText = text.toLowerCase();
  return crisisKeywords.some((keyword) => lowerText.includes(keyword));
}

export async function analyzeMood(
  text: string
): Promise<{ detectedMood: string; explanation: string }> {
  try {
    await ensureOllamaReady();

    const prompt = `Проанализируй текст и определи эмоциональное состояние человека одним словом из этого списка:
    - Amazing (восхитительно)
    - Good (хорошо)
    - Okay (нормально)
    - Low (плохо)
    - Stressed (стресс)
    
    Текст: "${text}"
    
    Ответь ТОЛЬКО в формате JSON, без дополнительного текста:
    {
      "mood": "Amazing|Good|Okay|Low|Stressed",
      "confidence": число от 0 до 1,
      "explanation": "краткое объяснение"
    }`;

    const response = await ollamaClient.post('/api/generate', {
      model: config.ollamaModel,
      prompt: prompt,
      stream: false,
    });

    const responseText = response.data.response;

    // Парсим JSON из ответа
    const jsonMatch = responseText.match(/\{[\s\S]*\}/);
    if (!jsonMatch) {
      console.warn('Не удалось распарсить JSON ответ:', responseText);
      // Возвращаем значение по умолчанию если не смогли распарсить
      return {
        detectedMood: 'Okay',
        explanation: 'Не удалось определить точное настроение',
      };
    }

    const analysisResult = JSON.parse(jsonMatch[0]);

    return {
      detectedMood: analysisResult.mood,
      explanation: analysisResult.explanation,
    };
  } catch (error) {
    console.error('Ошибка при анализе настроения:', error);
    // Возвращаем значение по умолчанию вместо выброса ошибки
    return {
      detectedMood: 'Okay',
      explanation: 'Не удалось проанализировать настроение',
    };
  }
}

/**
 * Автоматически транскрибировать голосовое сообщение используя ИИ
 * Используется когда обычная транскрипция неудалась
 */
export async function aiTranscribeVoice(
  context?: ConversationContext & { audioFilePath?: string }
): Promise<string> {
  try {
    await ensureOllamaReady();

    let transcriptionPrompt = 'Что сказано в этом голосовом сообщении? Попытайся транскрибировать максимально точно.';
    
    // Если есть контекст - используй его для улучшения транскрипции
    if (context?.conversationHistory && context.conversationHistory.length > 0) {
      const recentMessages = context.conversationHistory.slice(-2).map(msg => `${msg.role}: ${msg.content}`).join('\n');
      transcriptionPrompt += `\n\nРецент контекст беседы:\n${recentMessages}\n\nИспользуй этот контекст чтобы лучше понять, о чём говорит пользователь.`;
    }

    const response = await ollamaClient.post('/api/generate', {
      model: config.ollamaModel,
      prompt: transcriptionPrompt,
      stream: false,
    });

    const transcribedText = response.data.response;
    
    console.log('✅ AI Transcription completed:', transcribedText.substring(0, 80) + '...');
    return transcribedText;
  } catch (error) {
    console.error('Ошибка при ИИ транскрипции:', error);
    throw new Error('Не удалось выполнить ИИ транскрипцию');
  }
}
