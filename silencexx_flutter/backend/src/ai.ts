// Initialize Ollama client
const ollamaClient: AxiosInstance = axios.create({
  baseURL: config.ollamaUrl,
  timeout: 180000, // 180 seconds timeout for long responses (mistral is slow on Windows)
});

// Model loading state
let ollamaReady = false;
let modelLoaded = false;
let unloadTimer: NodeJS.Timeout | null = null;

// Test Ollama connection
async function ensureOllamaReady(): Promise<void> {
  if (ollamaReady) return;

  try {
    console.log(`🔍 Проверка подключения к Ollama: ${config.ollamaUrl}`);
    const response = await ollamaClient.get('/api/tags', { timeout: 5000 });
    
    if (!response.data.models || response.data.models.length === 0) {
      throw new Error(`В Ollama нет загруженных моделей. Используйте: ollama pull ${config.ollamaModel}`);
    }

    const modelExists = response.data.models.some((m: any) => m.name.includes(config.ollamaModel));
    if (!modelExists) {
      throw new Error(`Модель ${config.ollamaModel} не загружена. Используйте: ollama pull ${config.ollamaModel}`);
    }

    console.log(`✅ Ollama подключена! Доступные модели:`, response.data.models.map((m: any) => m.name));
    ollamaReady = true;
  } catch (error) {
    console.error('❌ Ошибка подключения к Ollama:');
    console.error('   Убедитесь, что Ollama запущена: ollama serve');
    console.error('   URL:', config.ollamaUrl);
    throw error;
  }
}

// Lazy load model with auto-unload
async function ensureModelLoaded(): Promise<void> {
  if (modelLoaded) {
    // Reset unload timer
    if (unloadTimer) clearTimeout(unloadTimer);
    
    unloadTimer = setTimeout(() => {
      modelLoaded = false;
      console.log('🔄 Model unloaded after 5 minutes of inactivity');
    }, 300000); // 5 minutes
    
    return;
  }

  try {
    // Load model by doing a warmup request
    console.log('⏳ Loading model... (first request may be slow)');
    modelLoaded = true;
    
    // Set unload timer
    if (unloadTimer) clearTimeout(unloadTimer);
    unloadTimer = setTimeout(() => {
      modelLoaded = false;
      console.log('🔄 Model unloaded after 5 minutes of inactivity');
    }, 300000);
    
  } catch (error) {
    modelLoaded = false;
    throw error;
  }
}

